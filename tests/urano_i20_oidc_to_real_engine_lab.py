def attested_cgroup_empty(unit: str, group: str) -> bool:
    """Inspect ONLY an already-attested I20 user service; never cgroup root."""
    if not re.fullmatch(r'montara-i20-lab-[0-9a-f]{12}', unit):
        raise ValueError('Unrecognized I20 lab unit')
    uid = os.getuid()
    expected = (f'/user.slice/user-{uid}.slice/user@{uid}.service/'
                f'app.slice/{unit}.service')
    if group != expected:
        raise ValueError('Unrecognized target cgroup identity')
    procs = Path('/sys/fs/cgroup') / group.lstrip('/') / 'cgroup.procs'
    try:
        return not procs.read_text().split()
    except FileNotFoundError:
        # systemd has unloaded the attested unit and removed its cgroup.
        return True


class CgroupLabExecutor:
    """Only for one opt-in synthetic owner; public runtime MUST NOT use this."""
    def __init__(self, guard, repo, engine, venv, workspace):
        self.guard=guard
        self.repo=repo
        self.engine=engine
        self.venv=venv
        self.workspace=workspace
        self.slots={}
        self.active={}
        self.last_peak_mib=None

    def runtime_for_owner(self,owner):
        return self.slots.get(owner)

    def _properties(self,unit):
        output=subprocess.check_output(['systemctl','--user','show',unit+'.service',
            '-p','MemoryMax','-p','TasksMax','-p','CPUQuotaPerSecUSec',
            '-p','ControlGroup','-p','MemoryPeak','-p','ActiveState'],text=True,timeout=9)
        return dict(line.split('=',1) for line in output.splitlines() if '=' in line)

    def _packet(self,proc,timeout=40):
        readers,_,_=select.select([proc.stdout],[],[],timeout)
        if not readers:raise TimeoutError('Engine protocol timed out')
        line=proc.stdout.readline(8193)
        if not line or len(line)>8192:raise RuntimeError('Engine protocol unavailable')
        return json.loads(line)

    def open_verified(self,owner,ticket):
        if owner not in self.slots or self.slots[owner]!=ticket.runtime_id:
            raise ValueError('Wrong trusted runtime')
        if ticket.project_path.parent != self.workspace/'Projects':
            raise ValueError('Workspace outside owner root')
        if owner in self.active:
            raise RuntimeError('Owner worker already exists')
        unit='montara-i20-lab-'+uuid.uuid4().hex[:12]
        # The *unit* is generated by the trusted controller, NOT from HTTP.
        root=tempfile.TemporaryDirectory(prefix='montara-i15-lab.',dir='/tmp')
        pyroot=Path(sys.executable).resolve().parent.parent.parent
        command=['systemd-run','--user','--pipe','--wait','--collect','--quiet',
                 '--unit='+unit,'--property=MemoryMax=512M',
                 '--property=TasksMax=32','--property=CPUQuota=100%',
                 '--property=TimeoutStopSec=3s','--property=KillMode=control-group',
                 '--property=SendSIGKILL=yes',
                 'unshare','--user','--map-root-user','--mount','--net','--pid','--fork','--',
                 str(self.repo/'tests'/'urano_i15_namespace_entry.sh'),
                 '--worker',root.name,str(self.workspace),str(self.repo),
                 str(self.engine),str(self.venv),str(pyroot)]
        proc=subprocess.Popen(command,stdin=subprocess.PIPE,stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,bufsize=0,start_new_session=True,
            env={**os.environ,'PYTHONPATH':str(self.repo)})
        self.active[owner]=(unit,proc,root,None)
        ready=self._packet(proc)
        if ready.get('type')!='ready' or ready.get('worker_pid')!=1:
            raise RuntimeError('PID namespace handshake invalid')
        properties=self._properties(unit)
        if (properties.get('MemoryMax')!=str(512*1048576) or
            properties.get('TasksMax')!='32' or
            properties.get('CPUQuotaPerSecUSec')!='1s' or
            not properties.get('ControlGroup','').endswith('/'+unit+'.service') or
            properties.get('ActiveState')!='active'):
            raise RuntimeError('Private cgroup boundaries not verified')
        # Save the kernel cgroup identity BEFORE systemd unloads the unit.
        self.active[owner]=(unit,proc,root,properties['ControlGroup'])
        self.last_peak_mib=round(int(properties.get('MemoryPeak') or 0)/1048576,2)
        proc.stdin.write((json.dumps({'op':'open','folder':ticket.project_path.name})+'\n').encode())
        proc.stdin.flush()
        opened=self._packet(proc)
        return (opened.get('ok') is True and opened.get('type')=='opened' and
                opened.get('folder')==ticket.project_path.name)

    def abort(self,owner,runtime_id):
        if self.slots.get(owner)!=runtime_id:
            raise ValueError('Wrong trusted runtime')
        active=self.active.get(owner)
        if active is None:return
        unit,proc,root,group=active
        try:
            stop=subprocess.run(['systemctl','--user','stop','--no-block',unit+'.service'],
                capture_output=True,timeout=7)
            if stop.returncode:
                raise RuntimeError('Private cgroup stop rejected')
            proc.wait(timeout=12)
            for _ in range(15):
                props=self._properties(unit)
                # Use the attested saved group. Once systemd unloads the unit,
                # `ControlGroup` is blank and must NEVER resolve to cgroup root.
                if props.get('ActiveState') not in ('active','activating') and \
                        attested_cgroup_empty(unit, group):
                    self.active.pop(owner,None)
                    root.cleanup()
                    return
                time.sleep(0.2)
            raise RuntimeError('Engine cgroup not fully reaped')
        finally:
            if proc.poll() is not None:
                if proc.stdin and not proc.stdin.closed:proc.stdin.close()
                if proc.stdout:proc.stdout.close()


def verified_fake_login(client,google,owner_store,*,sub,email):
    google.sub,google.email=sub,email
    response=client.get('/urano/v1/google/start',base_url=HOST)
    assert response.status_code==302
    values={k:v[0] for k,v in parse_qs(urlsplit(response.headers['Location']).query).items()}
    google.nonce=values['nonce'];google.expected_challenge=values['code_challenge']
    google.code='i20-synthetic-provider-code'
    callback=client.get('/urano/v1/google/callback',base_url=HOST,
        query_string={'state':values['state'],'code':google.code})
    assert callback.status_code==303,callback.get_data(as_text=True)[:120]
    # Only the offline operator reads this isolated fake provider DB.
    with owner_store._connect() as db:
        row=db.execute('SELECT owner_id FROM urano_google_owners WHERE google_sub=?',(sub,)).fetchone()
    return str(row['owner_id'])


def probe(repo,engine,venv):
    sha=subprocess.check_output(['git','-C',str(repo),'rev-parse','HEAD:engine'],text=True).strip()
    current=subprocess.check_output(['git','-C',str(engine),'rev-parse','HEAD'],text=True).strip()
    if sha!=current:raise ValueError('Engine not pinned to repository')
    begin=time.monotonic()
    with tempfile.TemporaryDirectory(prefix='montara-i20-oidc.',dir='/tmp') as private_root, \
         tempfile.TemporaryDirectory(prefix='montara-i15-workspace.',dir='/tmp') as physical_root:
        private=Path(private_root);workspace=Path(physical_root)
        catalog=ProjectCatalog(private/'projects.sqlite3')
        (workspace/'Projects').mkdir()
        bindings=EngineProjectRegistry(private/'bindings.sqlite3',workspace,catalog)
        guard=RuntimeActivationGuard(private/'runtime.sqlite3',catalog,bindings)
        executor=CgroupLabExecutor(guard,repo,engine,venv,workspace)
        google=SignedFakeGoogle()
        app=create_owner_api(private,settings=OIDCSettings(CLIENT,'fake-secret',CALLBACK,
            frozenset({'alpha@example.test','beta@example.test'})),provider=google,
            engine_gateway=OwnerEngineGateway(catalog,guard,executor))
        alpha=app.test_client();beta=app.test_client()
        owners=GoogleOwnerStore(private/'owners.sqlite3')
        owner=verified_fake_login(alpha,google,owners,sub='i20-google-sub-a',email='alpha@example.test')
        foreign=verified_fake_login(beta,google,owners,sub='i20-google-sub-b',email='beta@example.test')
        assert owner!=foreign
        runtime=guard.register_trusted(owner);executor.slots[owner]=runtime
        project=catalog.create(owner,'I20 Engine Project')
        sys.path.insert(0,str(engine))
        try:
            from core.project import new_project_document
            folder=workspace/'Projects'/'I20-Synthetic'
            folder.mkdir()
            (folder/'project.json').write_text(json.dumps(new_project_document('I20-Synthetic')))
        finally:sys.path.remove(str(engine))
        bindings.bind_trusted(owner,project.id,'I20-Synthetic')
        path='/urano/v1/projects/'+project.id+'/open'
        a_csrf=alpha.post('/urano/v1/session/refresh',base_url=HOST,
                            headers={'Origin':HOST}).json['csrf']
        b_csrf=beta.post('/urano/v1/session/refresh',base_url=HOST,
                            headers={'Origin':HOST}).json['csrf']
        unknown=beta.post(path,base_url=HOST,
            headers={'Origin':HOST,'X-Urano-CSRF':b_csrf,'X-Owner-ID':owner})
        assert unknown.status_code==404
        anonymous=app.test_client().post(path,base_url=HOST,headers={'Origin':HOST})
        assert anonymous.status_code==401
        missing_csrf=alpha.post(path,base_url=HOST,headers={'Origin':HOST})
        assert missing_csrf.status_code==403
        result={'signed_google_fake_owner':True,'cross_owner_http_404':True,
                'anonymous_http_401':True,'missing_csrf_http_403':True,
                'real_engine_open':False,'host_uid_per_tenant_isolated':False,
                'public_beta_modified':False,'companion_tested':False,
                'video_export_tested':False,'pinned_engine_sha':sha}
        try:
            response=alpha.post(path,base_url=HOST,headers={
                'Origin':HOST,'X-Urano-CSRF':a_csrf,'X-Owner-ID':foreign})
            if response.status_code!=200:
                raise RuntimeError('I13 real Engine open rejected: HTTP '+str(response.status_code))
            if response.json.get('state')!='ready' or response.json.get('project_id')!=project.id:
                raise RuntimeError('I13 returned invalid opened state')
            state=guard.get_state(owner,runtime)
            if state[:2]!=('ready',project.id):
                raise RuntimeError('Runtime guard not acknowledged')
            result['real_engine_open']=True
            result['open_from_google_session_seconds']=round(time.monotonic()-begin,3)
            result['memory_peak_during_handshake_mib']=executor.last_peak_mib
        finally:
            executor.abort(owner,runtime)
            state,_,generation=guard.get_state(owner,runtime)
            if state=='ready':guard.invalidate_after_worker_exit(owner,runtime,generation)
        result['engine_fully_reaped']=owner not in executor.active
        result['runtime_idle_after_cleanup']=guard.get_state(owner,runtime)[0]=='idle'
        result['elapsed_seconds']=round(time.monotonic()-begin,3)
        return result


